/**
 * Publishes the catalogues, so nothing has to keep a second copy of them.
 *
 *   node scripts/sync-catalogue.mjs [--check]
 *
 * Two lists in this repo are read by more than one program: the modules a city
 * can run, and the roles an account can hold. Each is declared in exactly one
 * JSON file here, and from it this writes two things:
 *
 *   src/utils/<name>Keys.ts   the key union, so a typo in the app is a compile
 *                             error rather than a value that silently matches
 *                             nothing. Generated, and committed.
 *   config/<name>             the same list in Firestore, which the admin
 *                             console renders from. The console keeps no list
 *                             of its own, so it cannot drift.
 *
 * Why not let Firestore be the source outright: neither list is just names. A
 * module is a screen and a role is a set of security rules — adding
 * "בית עלמין" or "מנהל בית עלמין" to a document creates neither, so only this
 * repo can say what exists. This makes the console learn the list instead of
 * restating it.
 *
 * ROLES ARE THE REASON THIS SCRIPT IS PLURAL. The modules list was unified
 * first; the roles list was not, and within a day the console had gone stale in
 * two ways at once — it had never heard of content_admin, so a city_admin could
 * not delegate it, and its ROLE_PRIORITY (commented "mirrors the app") would
 * have quietly demoted anyone who held it on the next save. One list unified
 * and the other left alone is not a fix, it is a coin flip about which one bites.
 *
 * --check verifies the generated files are current without writing or
 * publishing, for running before a build.
 */
import { initializeApp, cert } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';
import { readFileSync, writeFileSync } from 'fs';

const CHECK = process.argv.includes('--check');

/**
 * type   the exported TypeScript union name
 * note   lines of comment explaining the union, written into the generated file
 * check  extra validation beyond key/label, returning an error string or null
 */
const CATALOGUES = [
  {
    name: 'modules',
    source: 'src/utils/moduleCatalogue.json',
    keys: 'src/utils/moduleKeys.ts',
    type: 'ModuleKey',
    note: [
      'The union exists so a mistyped module key is a compile error instead of',
      'a key that quietly matches nothing.',
    ],
    check: (m) =>
      m.kind !== 'section' && m.kind !== 'feature'
        ? `${m.key}: kind must be "section" or "feature"`
        : null,
  },
  {
    name: 'roles',
    source: 'src/utils/roleCatalogue.json',
    keys: 'src/utils/roleKeys.ts',
    type: 'UserRole',
    note: [
      'ORDER IS PRIORITY, highest authority first. computePrimaryRole walks it to',
      'collapse a role set down to the single `role` field the rules read, so',
      'reordering an entry changes which role an account reports as its primary.',
    ],
    check: (r) =>
      r.assignableBy !== 'city_admin' && r.assignableBy !== 'super_admin'
        ? `${r.key}: assignableBy must be "city_admin" or "super_admin"`
        : null,
  },
];

let stale = false;

for (const cat of CATALOGUES) {
  const list = JSON.parse(readFileSync(cat.source, 'utf8'));
  if (!Array.isArray(list) || !list.length) {
    console.error(`${cat.source} is empty or not an array — refusing to publish.`);
    process.exit(1);
  }

  const seen = new Set();
  for (const entry of list) {
    if (!entry.key || !entry.label) {
      console.error(`${cat.source}: entry missing key/label: ${JSON.stringify(entry)}`);
      process.exit(1);
    }
    if (seen.has(entry.key)) {
      console.error(`${cat.source}: duplicate key "${entry.key}"`);
      process.exit(1);
    }
    seen.add(entry.key);
    const err = cat.check?.(entry);
    if (err) {
      console.error(`${cat.source}: ${err}`);
      process.exit(1);
    }
  }

  const generated = [
    '// GENERATED by scripts/sync-catalogue.mjs — do not edit.',
    `// The source is ${cat.source}; run \`node scripts/sync-catalogue.mjs\` after`,
    '// changing it.',
    ...cat.note.map((line) => `// ${line}`),
    `export type ${cat.type} =`,
    ...list.map((e) => `  | '${e.key}'`),
  ].join('\n') + ';\n';

  const current = (() => {
    try { return readFileSync(cat.keys, 'utf8'); } catch { return null; }
  })();

  if (CHECK) {
    if (current?.replace(/\r\n/g, '\n') !== generated) {
      console.error(`${cat.keys} is out of date — run: node scripts/sync-catalogue.mjs`);
      stale = true;
    } else {
      console.log(`${cat.keys} is current (${list.length} entries).`);
    }
    continue;
  }

  writeFileSync(cat.keys, generated);
  console.log(`wrote ${cat.keys} (${list.length} entries)`);
  cat.list = list;
}

if (CHECK) process.exit(stale ? 1 : 0);

initializeApp({ credential: cert(JSON.parse(readFileSync('scripts/serviceAccount.json', 'utf8'))) });
const db = getFirestore();

for (const cat of CATALOGUES) {
  await db.collection('config').doc(cat.name).set({
    [cat.name]: cat.list,
    updatedAt: new Date().toISOString(),
  });
  console.log(`published to config/${cat.name}`);
}
console.log('the console picks these up on its next load');
